"""Write schema.sql (Postgres DDL) from the SQLAlchemy models, so the two never drift apart.
The app also creates these tables automatically on startup.

    python scripts/export_schema.py > schema.sql
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from sqlalchemy.dialects import postgresql  # noqa: E402
from sqlalchemy.schema import CreateIndex, CreateTable  # noqa: E402

from app.models import Base  # noqa: E402

dialect = postgresql.dialect()
print("-- Generated by scripts/export_schema.py. Do not edit by hand.\n")
for table in Base.metadata.sorted_tables:
    print(str(CreateTable(table).compile(dialect=dialect)).strip() + ";\n")
    for index in sorted(table.indexes, key=lambda i: i.name):
        print(str(CreateIndex(index).compile(dialect=dialect)).strip() + ";")
    print()
